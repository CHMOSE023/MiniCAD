    std::uint32_t Color::IndexRgb(std::int16_t index)
    {
        return index > 0 && index < 256 ? kIndexRgb[index] : 0;
    }

    std::int16_t Color::ApproxIndex() const
    {
        if (!IsTrueColor())
            return Index();

        // 按 RGB 欧氏距离找最近的 ACI 颜色（1～255）
        const std::uint32_t rgb = static_cast<std::uint32_t>(TrueColor());
        const int r = (rgb >> 16) & 0xFF, g = (rgb >> 8) & 0xFF, b = rgb & 0xFF;
        std::int16_t best = 7;
        int bestDistance = -1;
        for (int i = 1; i < 256; ++i)
        {
            const int dr = r - static_cast<int>((kIndexRgb[i] >> 16) & 0xFF);
            const int dg = g - static_cast<int>((kIndexRgb[i] >> 8) & 0xFF);
            const int db = b - static_cast<int>(kIndexRgb[i] & 0xFF);
            const int distance = dr * dr + dg * dg + db * db;
            if (bestDistance < 0 || distance < bestDistance)
            {
                best = static_cast<std::int16_t>(i);
                bestDistance = distance;
                if (distance == 0)
                    break;
            }
        }
        return best;
    }
